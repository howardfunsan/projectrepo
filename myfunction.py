def add_numbers(a, b):
    """
    Returns the sum of two numbers.
    
    Parameters:
    a (int or float): First number
    b (int or float): Second number
    
    Returns:
    int or float: The sum of a and b
    """
    return a + b

# Example usage:
if __name__ == "__main__":
    result = add_numbers(3, 5)
    print("Sum is:", result)
